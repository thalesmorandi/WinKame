    public static (RECT Work, double Scale) MonitorAt(POINT pt)
    {
        var mon = MonitorFromPoint(pt, MONITOR_DEFAULTTONEAREST);
        var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
        GetMonitorInfo(mon, ref info);
        double scale = 1;
        if (GetDpiForMonitor(mon, 0, out var dx, out _) == 0 && dx > 0) scale = dx / 96.0;
        return (info.rcWork, scale);
    }

    public static void AddExStyle(IntPtr hwnd, int style)
    {
        var cur = GetWindowLongPtr(hwnd, GWL_EXSTYLE).ToInt64();
        SetWindowLongPtr(hwnd, GWL_EXSTYLE, new IntPtr(cur | (long)style));
    }

    /// <summary>
    /// Windows only lets the process that got the last input take focus. A no-op mouse input
    /// counts as input, which is the same trick PowerToys uses.
    /// </summary>
    public static void ForceForeground(IntPtr hwnd)
    {
        var inputs = new[] { new INPUT { type = INPUT_MOUSE, U = new InputUnion { mi = new MOUSEINPUT { dwExtraInfo = OurExtraInfo } } } };
        SendInput(1, inputs, Marshal.SizeOf<INPUT>());
        SetForegroundWindow(hwnd);
    }

    /// <summary>Sends an unassigned key so a tapped Alt doesn't open the menu bar of the app under the cursor.</summary>
    public static void SendDummyKey()
    {
        const ushort VK_NONAME = 0xFC;
        var inputs = new[]
        {
            new INPUT { type = INPUT_KEYBOARD, U = new InputUnion { ki = new KEYBDINPUT { wVk = VK_NONAME, dwExtraInfo = OurExtraInfo } } },
            new INPUT { type = INPUT_KEYBOARD, U = new InputUnion { ki = new KEYBDINPUT { wVk = VK_NONAME, dwFlags = KEYEVENTF_KEYUP, dwExtraInfo = OurExtraInfo } } },
        };
        SendInput(2, inputs, Marshal.SizeOf<INPUT>());
    }
